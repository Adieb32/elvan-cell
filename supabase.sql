-- ---------- PROFIL PENGGUNA ----------
create table if not exists public.profiles (
  id uuid primary key references auth.users on delete cascade,
  username text unique not null,
  full_name text,
  role text not null default 'none' check (role in ('admin', 'kasir', 'none')),
  created_at timestamptz default now()
);

create or replace function public.my_role() returns text
language sql stable security definer set search_path = public as $$
  select role from public.profiles where id = auth.uid()
$$;
create or replace function public.my_username() returns text
language sql stable security definer set search_path = public as $$
  select username from public.profiles where id = auth.uid()
$$;
create or replace function public.is_staff() returns boolean
language sql stable as $$ select coalesce(public.my_role() in ('admin', 'kasir'), false) $$;
create or replace function public.is_admin() returns boolean
language sql stable as $$ select coalesce(public.my_role() = 'admin', false) $$;

-- Profil dibuat otomatis saat user dibuat.
-- User PERTAMA otomatis jadi admin; user berikutnya nonaktif sampai diaktifkan admin.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, username, full_name, role)
  values (
    new.id,
    lower(coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1))),
    coalesce(new.raw_user_meta_data->>'full_name', split_part(new.email, '@', 1)),
    case when exists (select 1 from public.profiles) then 'none' else 'admin' end
  );
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- DATA ----------
create table if not exists public.settings (
  key text primary key,
  value text
);
insert into public.settings (key, value) values ('counter_name', 'Elvan Cell') on conflict do nothing;

create table if not exists public.daily_opening (
  date text primary key,
  cash bigint not null default 0,
  digital bigint not null default 0,
  updated_by text default public.my_username()
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  datetime text not null,
  type text not null,
  nominal bigint not null default 0 check (nominal >= 0),
  admin_fee bigint not null default 0 check (admin_fee >= 0),
  cash_in bigint not null default 0 check (cash_in >= 0),
  cash_out bigint not null default 0 check (cash_out >= 0),
  digital_in bigint not null default 0 check (digital_in >= 0),
  digital_out bigint not null default 0 check (digital_out >= 0),
  method text,
  note text,
  created_by text default public.my_username(),
  created_at timestamptz default now()
);
create index if not exists idx_tx_datetime on public.transactions (datetime);

create table if not exists public.accounts (
  id bigint generated by default as identity primary key,
  name text not null,
  initial_balance bigint not null default 0
);

create table if not exists public.mutations (
  id bigint generated by default as identity primary key,
  datetime text not null,
  type text not null check (type in ('in', 'out', 'transfer')),
  account_id bigint references public.accounts on delete cascade,
  to_account_id bigint references public.accounts on delete cascade,
  amount bigint not null check (amount > 0),
  note text,
  created_by text default public.my_username()
);

-- Saldo per rekening (dihitung otomatis)
create or replace view public.account_balances with (security_invoker = on) as
select a.id, a.name, a.initial_balance,
  a.initial_balance
  + coalesce((select sum(amount) from public.mutations m where m.type = 'in' and m.account_id = a.id), 0)
  - coalesce((select sum(amount) from public.mutations m where m.type = 'out' and m.account_id = a.id), 0)
  - coalesce((select sum(amount) from public.mutations m where m.type = 'transfer' and m.account_id = a.id), 0)
  + coalesce((select sum(amount) from public.mutations m where m.type = 'transfer' and m.to_account_id = a.id), 0)
  as balance
from public.accounts a;

