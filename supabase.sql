alter table public.profiles enable row level security;
alter table public.settings enable row level security;
alter table public.daily_opening enable row level security;
alter table public.transactions enable row level security;
alter table public.accounts enable row level security;
alter table public.mutations enable row level security;

drop policy if exists p_profiles_read on public.profiles;
create policy p_profiles_read on public.profiles for select to authenticated
  using (id = auth.uid() or public.is_staff());
drop policy if exists p_profiles_admin on public.profiles;
create policy p_profiles_admin on public.profiles for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- settings, saldo awal, transaksi, mutasi: semua staf (admin & kasir)
do $$
declare t text;
begin
  foreach t in array array['settings', 'daily_opening', 'transactions', 'mutations'] loop
    execute format('drop policy if exists p_staff on public.%I', t);
    execute format('create policy p_staff on public.%I for all to authenticated using (public.is_staff()) with check (public.is_staff())', t);
  end loop;
end $$;

-- rekening: staf boleh lihat/tambah, hanya admin boleh hapus/ubah
drop policy if exists p_acc_read on public.accounts;
create policy p_acc_read on public.accounts for select to authenticated using (public.is_staff());
drop policy if exists p_acc_insert on public.accounts;
create policy p_acc_insert on public.accounts for insert to authenticated with check (public.is_staff());
drop policy if exists p_acc_admin on public.accounts;
create policy p_acc_admin on public.accounts for update to authenticated using (public.is_admin());
drop policy if exists p_acc_delete on public.accounts;
create policy p_acc_delete on public.accounts for delete to authenticated using (public.is_admin());

-- ---------- FUNGSI ADMIN ----------
-- Hapus semua transaksi pada satu tanggal (khusus admin)
create or replace function public.clear_day(p_date text) returns integer
language plpgsql security invoker as $$
declare n integer;
begin
  if not public.is_admin() then raise exception 'Khusus admin'; end if;
  delete from public.transactions where left(datetime, 10) = p_date;
  get diagnostics n = row_count;
  return n;
end $$;

-- Pulihkan dari file backup (khusus admin, semua-atau-tidak-sama-sekali)
create or replace function public.restore_backup(data jsonb) returns void
language plpgsql security invoker as $$
begin
  if not public.is_admin() then raise exception 'Khusus admin'; end if;
  if data->>'app' <> 'elvan-cell' then raise exception 'File backup tidak valid'; end if;

  delete from public.transactions where true;
  delete from public.mutations where true;
  delete from public.accounts where true;
  delete from public.daily_opening where true;
  delete from public.settings where true;

  insert into public.settings select * from jsonb_populate_recordset(null::public.settings, coalesce(data->'settings', '[]'));
  insert into public.daily_opening select * from jsonb_populate_recordset(null::public.daily_opening, coalesce(data->'daily_opening', '[]'));
  insert into public.accounts select * from jsonb_populate_recordset(null::public.accounts, coalesce(data->'accounts', '[]'));
  insert into public.mutations select * from jsonb_populate_recordset(null::public.mutations, coalesce(data->'mutations', '[]'));
  insert into public.transactions (id, datetime, type, nominal, admin_fee, cash_in, cash_out, digital_in, digital_out, method, note, created_by)
    select id, datetime, type, nominal, admin_fee, cash_in, cash_out, digital_in, digital_out, method, note, created_by
    from jsonb_populate_recordset(null::public.transactions, coalesce(data->'transactions', '[]'));

  perform setval(pg_get_serial_sequence('public.transactions', 'id'), coalesce((select max(id) from public.transactions), 0) + 1, false);
  perform setval(pg_get_serial_sequence('public.mutations', 'id'), coalesce((select max(id) from public.mutations), 0) + 1, false);
  perform setval(pg_get_serial_sequence('public.accounts', 'id'), coalesce((select max(id) from public.accounts), 0) + 1, false);
end $$;
